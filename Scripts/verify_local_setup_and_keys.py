    pawn(1).cancel_cast();await key('LeftMouseButton')
    check('reverse mouse primary reaches only P2',get(pawn(),'pending_cast')==-1 and get(pawn(1),'pending_cast')==0)
    pawn(1).cancel_cast();before=[pawn(i).get_actor_location() for i in [0,1]];await move(pad=0)
