    c.start_key_capture(0);await key('W');check('movement key can be rebound',key_name(0)=='W')
    c.start_key_capture(12);await key('K');c.start_key_capture(14);await key('B')
    check('shop and ready can be rebound',key_name(12)=='K' and key_name(14)=='B')
    reloaded=unreal.new_object(unreal.WarlockUserSettings);reloaded.load_settings(True)
    check('keyboard bindings survive config reload',str(reloaded.keyboard_key(4).get_editor_property('key_name'))=='Z' and str(reloaded.keyboard_key(0).get_editor_property('key_name'))=='W')
    c.start_key_capture(4);await key('Escape');check('Escape cancels capture and keeps pause',get(c,'waiting_binding')==-1 and unreal.GameplayStatics.is_game_paused(w) and key_name(4)=='Z')
    c.start_key_capture(4);await key('BackSpace');check('Backspace cancels capture',get(c,'waiting_binding')==-1 and key_name(4)=='Z')
