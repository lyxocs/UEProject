checks=[];path=Path(unreal.Paths.project_saved_dir(),'Validation','local-setup-keys.json')
def get(o,k):return o.get_editor_property(k)
def check(name,value):
    if not value:
        path.write_text(json.dumps({'passed':len(checks),'failed':name,'checks':checks},indent=2),encoding='utf8');raise AssertionError(name)
    checks.append(name)
def pc(i=0):return unreal.GameplayStatics.get_player_controller(w,i)
def pawn(i=0):return next((p for p in actors(w,unreal.WarlockPawn) if p.get_controller()==pc(i)),None)
def state(i=0):return get(pc(i),'player_state')
def key_name(i):return str(settings.keyboard_key(i).get_editor_property('key_name'))
def pause(value=True):unreal.GameplayStatics.set_game_paused(w,value)
async def key(name,pad=None):
    if pad is None:view.inject_local_key(name,True)
    else:view.inject_pad_key(name,pad,True)
    await asyncio.sleep(.025)
    if pad is None:view.inject_local_key(name,False)
    else:view.inject_pad_key(name,pad,False)
    await asyncio.sleep(.025)
async def move(keyboard=None,pad=None):
    def hold(dt):
        if pad is not None:view.inject_pad_axis('Gamepad_LeftX',pad,.8)
        return True
    if keyboard:view.inject_local_key(keyboard,True)
    ticker=unreal.register_ticker_callback(hold)
    try:await asyncio.sleep(.12)
    finally:
        unreal.unregister_ticker_callback(ticker)
        if keyboard:view.inject_local_key(keyboard,False)
        if pad is not None:view.inject_pad_axis('Gamepad_LeftX',pad,0)
    await asyncio.sleep(.04)
def reset_positions():
    for i in range(len(actors(w,unreal.WarlockController))):
        p=pawn(i)
        if p:p.reset_for_round(unreal.Vector(-350+i*700,0,0))
