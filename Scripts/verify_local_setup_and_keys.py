    check('solo refills third bot and four fighters',len(actors(w,unreal.WarlockPawn))==4 and sum(get(get(p,'player_state'),'bot') for p in actors(w,unreal.WarlockPawn))==3)
    check('count change starts clean match without stale gold',get(match,'phase')=='SHOP' and get(match,'round')==0 and get(state(),'gold')==20)
    check('solo may choose a nonfirst pad exclusively',get(c,'local_control')==3 and get(c,'local_pad_index')==1)
    c.configure_local_players(1);await key('BackSpace');check('back at first claim returns to player settings',not get(view,'assigning_devices') and get(c,'players_menu_open'))
    c.configure_local_players(1);await key('Enter');c.open_pause_page(3);c.start_key_capture(4);await key('Z')
