    await key('Gamepad_FaceButton_Bottom',1)
    check('P1 may claim second enumerated pad',get(view,'join_seat')==1 and list(get(view,'pending_devices'))==[1,-2])
    await key('Gamepad_FaceButton_Bottom',1)
    check('same pad cannot also claim P2',get(view,'join_seat')==1 and get(view,'assigning_devices'))
    await key('BackSpace');check('keyboard back removes previous claim',get(view,'join_seat')==0 and list(get(view,'pending_devices'))==[-2,-2])
    await key('Gamepad_FaceButton_Bottom',0);await key('Gamepad_FaceButton_Bottom',1)
    check('two pads own separate explicit slots',get(c,'local_control')==3 and get(pc(1),'local_control')==3 and get(c,'local_pad_index')==0 and get(pc(1),'local_pad_index')==1)
    check('completion remains paused and does not cast A skill',unreal.GameplayStatics.is_game_paused(w) and get(pawn(),'pending_cast')==-1 and get(pawn(1),'pending_cast')==-1)
    pause(False);await asyncio.sleep(.15);reset_positions();before=[pawn(i).get_actor_location() for i in [0,1]]
    await move(pad=0);check('pad zero moves only P1',(pawn().get_actor_location()-before[0]).length()>1 and (pawn(1).get_actor_location()-before[1]).length()<.1)
    before=[pawn(i).get_actor_location() for i in [0,1]];await move(pad=1)
    check('pad one moves only P2',(pawn().get_actor_location()-before[0]).length()<.1 and (pawn(1).get_actor_location()-before[1]).length()>1)
    before=[pawn(i).get_actor_location() for i in [0,1]];await move(keyboard='Up')
