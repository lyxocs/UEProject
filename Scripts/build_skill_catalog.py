"""Generate runtime purchasing/cooldown data from the immutable extracted map.

Skill behaviour stays in C++; this file does not execute map scripts.
"""
import hashlib,json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
MAP=ROOT/'Warlock1.00b CN.w3x'
assert hashlib.sha256(MAP.read_bytes()).hexdigest()=='f1e5af933797d6936dd6040fd718fffec06a88c06707007583b7539e0fefe981'
data=json.loads((ROOT/'Analysis/Warlock1.00b CN/reference_data.json').read_text(encoding='utf-8'))
# Stable IDs retain the prototype's eight slots and legacy Haste purchase ID.
ids=['S000','S001','S002','S011','S015','S008','S005','S019','S007','S004','S003','S012','S013','S014','S016','S010','S009','S030','S006','S048','S017','S018','S050']
skills={s['ability_id']:s for s in data['skills']}
slots={'D':2,'R':3,'T':4,'E':5,'C':6,'Y':7}
names=['火球','天罚']+[skills[k]['name'] for k in ids[2:]]
def fl(v):return format(round(float(v),5),'.6g')+'f' if '.' in format(round(float(v),5),'.6g') else str(int(round(float(v))))+'.f'
out=['// Generated by Scripts/build_skill_catalog.py; source map SHA256 f1e5af933797d6936dd6040fd718fffec06a88c06707007583b7539e0fefe981.','#pragma once','namespace WarlockCatalogData {','struct FEntry {const TCHAR* Name;const TCHAR* MapId;int Slot,Learn,Upgrade,Cap;bool Dual;float CD[20];int RangeGate[10],MasteryGate[10];};','inline const FEntry Entries[]={']
dual={'S011','S012','S013','S014','S015','S016','S008','S010','S009','S019','S017','S018','S050'}
for i,k in enumerate(ids):
 if i<2:
  out.append('{TEXT("'+names[i]+'"),TEXT("'+k+'"),'+str(i)+',0,3,'+str(10 if i==0 else 1)+',false,{'+','.join([fl(4.8 if i==0 else 3)]*20)+'},{0},{0}},');continue
 s=skills[k];a=s['ability_object']['fields'].get('acdn',{});u=s['upgrade_object']['fields'];req=u.get('greq',{});count=u.get('grqc',{})
 # Technology levels count upgrades after learning, rather than ability levels.
 rg=[];mg=[]
 for n in range(10):
  tech=req.get(str(n),'');need=int(count.get(str(n),'1')) if tech else 0
  assert not tech or tech in ('R00Y','R017'),(k,tech)
  rg.append(need if tech=='R00Y' else 0);mg.append(need if tech=='R017' else 0)
 out.append('{TEXT("%s"),TEXT("%s"),%d,%d,%d,%d,%s,{%s},{%s},{%s}},'%(names[i],k,slots[s['slot']],s['learn_gold_base'],s['upgrade_gold_base'],s['normal_level_cap'],'true' if k in dual else 'false',','.join(fl(a.get(str(n),0)) for n in range(1,21)),','.join(map(str,rg)),','.join(map(str,mg))))
out+=['};','}']
(ROOT/'Source/WarlockArena/WarlockCatalogData.h').write_text('\n'.join(out)+'\n',encoding='utf-8')
print('Generated',len(ids),'families from verified original map')
