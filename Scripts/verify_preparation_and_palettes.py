"""Real PIE preparation combat, transitions, and visual-only round palettes."""
import asyncio
import json
from pathlib import Path
import unreal

w=unreal.EditorLevelLibrary.get_game_world();assert w and 'UEDPIE_' in w.get_path_name()
actors=unreal.GameplayStatics.get_all_actors_of_class
mode=actors(w,unreal.WarlockMode)[0];match=actors(w,unreal.WarlockMatchState)[0]
c1=unreal.GameplayStatics.get_player_controller(w,0)
mode.restart_match(False);c1.add_mixed_player();await asyncio.sleep(.1)
c2=unreal.GameplayStatics.get_player_controller(w,1)
p1=next(p for p in actors(w,unreal.WarlockPawn) if p.get_editor_property('player_state')==c1.get_editor_property('player_state'))
p2=next(p for p in actors(w,unreal.WarlockPawn) if p.get_editor_property('player_state')==c2.get_editor_property('player_state'))
s1=p1.get_editor_property('player_state');s2=p2.get_editor_property('player_state')
arena=actors(w,unreal.WarlockArena)[0]
view=next(v for v in unreal.ObjectIterator(unreal.WarlockViewport) if not v.get_name().startswith('Default__'))
checks=[];path=Path(unreal.Paths.project_saved_dir(),'Validation','preparation-palettes.json')
def get(o,k):return o.get_editor_property(k)
def put(o,k,v):o.set_editor_property(k,v)
def near(a,b):return abs(a-b)<.01
def check(name,value):
    if not value:
        path.write_text(json.dumps({'passed':len(checks),'checks':checks,'failed':name},indent=2),encoding='utf8');raise AssertionError(name)
    checks.append(name)
def reset():
    unreal.GameplayStatics.set_game_paused(w,True)
    for c in [c1,c2]:put(c,'shop_open',False);put(c,'help_open',False)
    mode.restart_match(False);put(match,'remaining',500)
    p1.reset_for_round(unreal.Vector(-300,0,0));p2.reset_for_round(unreal.Vector(300,0,0))
async def tick(t=.1):
    unreal.GameplayStatics.set_game_paused(w,False);await asyncio.sleep(t);unreal.GameplayStatics.set_game_paused(w,True)
async def key(name,pad=None):
    unreal.GameplayStatics.set_game_paused(w,False)
    if pad is None:view.inject_local_key(name,True)
    else:view.inject_pad_key(name,pad,True)
    await asyncio.sleep(.08)
    if pad is None:view.inject_local_key(name,False)
    else:view.inject_pad_key(name,pad,False)
    await asyncio.sleep(.03);unreal.GameplayStatics.set_game_paused(w,True)
try:
    reset();before=p1.get_actor_location();await key('Right')
    check('keyboard moves during preparation',p1.get_actor_location().x>before.x+5 and get(match,'phase')=='SHOP')
    before=p1.get_actor_location();c1.toggle_shop();await key('Right')
    check('open shop suspends active movement',abs(p1.get_actor_location().x-before.x)<1)
    c1.toggle_shop();await key('Right')
    check('closing shop resumes practice movement',p1.get_actor_location().x>before.x+5)
    reset();put(s2,'levels',[1]*8);await key('Gamepad_FaceButton_Top',0)
    check('pad Y practices spray without readying',get(p2,'pending_cast')==4 and not get(s2,'ready'))
    p2.cancel_cast();await key('Gamepad_DPad_Up',0)
    check('pad Up readies only its own player during practice',get(s2,'ready') and not get(s1,'ready') and get(match,'phase')=='SHOP')
    reset();before=(get(s1,'gold'),get(s2,'gold'),get(s1,'points'),get(s2,'points'))
    p2.hit(p1,7,unreal.Vector(1,0,0),1)
    check('practice hit gives original 21 impulse and 7 K',near(get(p2,'momentum').x,21) and near(get(p2,'knockback'),7))
    check('practice hit does not change life',near(get(p1,'health'),100) and near(get(p2,'health'),100))
    p2.hit(p1,10000,unreal.Vector(),0)
    check('lethal practice hit cannot kill',get(p2,'alive') and near(get(p2,'health'),100))
    check('practice does not award gold or points',before==(get(s1,'gold'),get(s2,'gold'),get(s1,'points'),get(s2,'points')))
    check('practice hit triggers cosmetic feedback',get(p2,'impact_serial')>0)
    reset();p1.reset_for_round(unreal.Vector(-300,0,0));p2.reset_for_round(unreal.Vector(0,0,0))
    check('fireball starts real anticipation in SHOP',p1.cast(0) and get(p1,'pending_cast')==0)
    p1.cancel_cast();await key('G');check('raw keyboard can practice a spell',get(p1,'pending_cast')==0)
    await key('S');check('raw S cancels practice spell',get(p1,'pending_cast')==-1 and near(get(p1,'cooldowns')[0],0))
    p1.cast(0)
    for _ in range(12):p1.step_simulation(.03)
    for _ in range(18):mode.simulate_projectiles(.03)
    check('practice projectile actually connects without HP damage',get(p2,'knockback')>=7 and near(get(p2,'health'),100))
    reset();p1.reset_for_round(unreal.Vector(0,0,0));p2.reset_for_round(unreal.Vector(160,0,0));put(p1,'health',50)
    p1.cast(1)
    for _ in range(24):p1.step_simulation(.03)
    check('practice Smite has no self HP cost',near(get(p1,'health'),50))
    check('practice Smite pushes its target without damage',get(p2,'momentum').x>0 and near(get(p2,'health'),100))
    check('practice keeps regular skill cooldown',get(p1,'cooldowns')[1]>2.9)
    p1.reset_for_round(unreal.Vector(1500,0,0));put(p1,'health',50)
    for _ in range(20):p1.step_ground()
    check('preparation lava cannot remove life or add K',near(get(p1,'health'),50) and near(get(p1,'knockback'),0))
    p1.set_actor_location(unreal.Vector(1900,0,40),False,False);await tick()
    check('falling off practice area safely returns player',p1.get_actor_location().length()<1000 and get(p1,'alive') and near(get(p1,'health'),100))
    reset();mode.restart_match(True);p2.hit(p1,7,unreal.Vector(1,0,0),1)
    check('same-team humans can knock each other in preparation',get(s1,'team')==get(s2,'team') and get(p2,'momentum').x>0 and near(get(p2,'health'),100))
    mode.start_round();put(p2,'protection',0);p2.hit(p1,7,unreal.Vector(1,0,0),1)
    check('combat restores normal friendly-fire restriction',near(get(p2,'momentum').x,0) and near(get(p2,'health'),100))
    reset();p1.cast(1)
    for _ in range(24):p1.step_simulation(.03)
    p2.hit(p1,7,unreal.Vector(1,0,0),1);mode.start_round()
    check('fight starts with clean HP K cooldowns and momentum',near(get(p1,'health'),100) and near(get(p2,'knockback'),0) and not any(get(p1,'cooldowns')) and get(p2,'momentum').is_nearly_zero())
    check('fight restores four-second protection',near(get(p1,'protection'),4))
    check('fight clears practice projectiles',len(actors(w,unreal.WarlockProjectile))==0)
    reset();await tick();check('first preparation uses palette zero',get(arena,'palette_index')==0)
    boundary=next(c for c in arena.get_components_by_class(unreal.StaticMeshComponent) if get(c,'static_mesh') and get(c,'static_mesh').get_name()=='Plane')
    check('boundary material and mesh are loaded',boundary.get_material(0) is not None)
    mode.start_round();put(match,'phase','SHOP');put(match,'round',0);put(match,'remaining',500)
    for p in actors(w,unreal.WarlockPawn):put(p,'protection',1000)
    baseline=(get(s1,'gold'),get(s1,'levels'),get(p1,'health'),get(match,'arena_radius'))
    for r in range(1,5):
        put(match,'round',r);await tick()
        check(f'next preparation previews round {r+1} palette',get(arena,'palette_index')==r%4)
        put(match,'phase','FIGHT');put(match,'round',r+1);await tick()
        check(f'fight preserves previewed palette for round {r+1}',get(arena,'palette_index')==r%4)
        put(match,'phase','SHOP');put(match,'round',r)
    check('palette cycling does not change gold levels HP or radius',baseline==(get(s1,'gold'),get(s1,'levels'),get(p1,'health'),get(match,'arena_radius')))
    put(match,'arena_radius',1000);await tick()
    scale=boundary.get_world_scale()
    check(f'visual boundary follows actual safe radius {get(match,"arena_radius")} scale {scale}',near(scale.x,20) and near(scale.y,20))
    Path(path).write_text(json.dumps({'passed':len(checks),'checks':checks,'scope':'PIE plus raw keyboard events; map colors cosmetic, preparation behavior user-requested'},indent=2),encoding='utf8')
finally:
    mode.restart_match(False);unreal.GameplayStatics.set_game_paused(w,False)
