"""Raw keyboard/mouse/pad routing for hold aim, cancellation and per-player shop scroll."""
import asyncio,json
from pathlib import Path
import unreal
w=unreal.EditorLevelLibrary.get_game_world();assert w and 'UEDPIE_' in w.get_path_name()
actors=unreal.GameplayStatics.get_all_actors_of_class
mode=actors(w,unreal.WarlockMode)[0];match=actors(w,unreal.WarlockMatchState)[0]
match.set_editor_property('participant_count',4);mode.restart_match(False)
c1=unreal.GameplayStatics.get_player_controller(w,0);c1.add_mixed_player();await asyncio.sleep(.15)
c2=unreal.GameplayStatics.get_player_controller(w,1)
ps=list(actors(w,unreal.WarlockPawn));p1=next(p for p in ps if p.get_controller()==c1);p2=next(p for p in ps if p.get_controller()==c2)
view=next(v for v in unreal.ObjectIterator(unreal.WarlockViewport) if not v.get_name().startswith('Default__'))
s=unreal.GameUserSettings.get_game_user_settings();old=s.get_editor_property('cast_trigger_mode');checks=[]
def get(o,k):return o.get_editor_property(k)
def put(o,k,v):o.set_editor_property(k,v)
def guide_of(p):return next(x for x in p.get_components_by_class(unreal.StaticMeshComponent) if x.get_editor_property('only_owner_see'))
def check(name,value):
    if not value:
        info={'failed':name,'passed':len(checks),'checks':checks,'baseline':[globals().get('a'),globals().get('b')],'players':[{'serial':get(p,'cast_serial'),'pending':get(p,'pending_cast'),'cooldown0':get(p,'cooldowns')[0],'aiming':get(c,'aiming_slot'),'role':get(c,'local_control')} for c,p in [(c1,p1),(c2,p2)]]}
        Path(unreal.Paths.project_saved_dir(),'Validation','guided-shop-input-failure.json').write_text(json.dumps(info,indent=2),encoding='utf8')
        raise AssertionError(name)
    checks.append(name)
async def key(name,down,pad=None):
    unreal.GameplayStatics.set_game_paused(w,False)
    if pad is None:view.inject_local_key(name,down)
    else:view.inject_pad_key(name,pad,down)
    await asyncio.sleep(.045)
    unreal.GameplayStatics.set_game_paused(w,True)
async def tap(name,pad=None):await key(name,True,pad);await key(name,False,pad)
def reset():
    c1.cancel_targeting();c2.cancel_targeting()
    for fx in actors(w,unreal.WarlockProjectile)+actors(w,unreal.WarlockSpellFX):fx.destroy_actor()
    for i,p in enumerate(ps):
        p.reset_for_round(unreal.Vector(-150+i*300,0,0));put(p,'protection',1000)
        put(get(p,'player_state'),'levels',[1]*8);put(get(p,'player_state'),'gold',100)
    for c in [c1,c2]:put(c,'shop_open',False);put(c,'help_open',False)
    put(match,'phase','SHOP')
try:
    unreal.GameplayStatics.set_game_paused(w,False)
    for name in ['G','D','F','S','LeftMouseButton']:view.inject_local_key(name,False)
    for pad in [0,1]:
        for name in ['Gamepad_RightTrigger','Gamepad_FaceButton_Bottom','Gamepad_RightThumbstick']:view.inject_pad_key(name,pad,False)
    await asyncio.sleep(.1)
    put(s,'cast_trigger_mode',1);reset()
    serial=get(p1,'cast_serial');await key('G',True)
    check('holding keyboard fireball selects aiming without casting',get(c1,'aiming_slot')==0 and get(p1,'pending_cast')==-1 and get(p1,'cast_serial')==serial)
    guide=guide_of(p1)
    check('line guide is visible and has no collision',guide and guide.is_visible() and guide.get_collision_enabled()==unreal.CollisionEnabled.NO_COLLISION)
    check('guide belongs to its pawn and only its owner can see it',guide.get_owner()==p1 and get(guide,'only_owner_see'))
    check('P1 preview does not select or cast P2',get(c2,'aiming_slot')==-1 and get(p2,'pending_cast')==-1)
    await key('S',True);await key('S',False);await key('G',False)
    check('S cancels preview and later key release does not cast',get(c1,'aiming_slot')==-1 and get(p1,'cast_serial')==serial and not any(get(p1,'cooldowns')))
    reset();serial=get(p1,'cast_serial');await key('G',True);await key('G',False)
    check('release starts one real fireball anticipation',get(p1,'pending_cast')==0 and get(p1,'cast_serial')==serial+1)
    for _ in range(12):p1.step_simulation(.03)
    check('released fireball still respects windup then produces one projectile',len(actors(w,unreal.WarlockProjectile))==1)
    await key('G',False);check('duplicate release cannot double-cast',get(p1,'cast_serial')==serial+1)
    reset();serial=get(p1,'cast_serial');c1.set_mouse_location(300,320)
    await key('D',True);await key('LeftMouseButton',True);await key('LeftMouseButton',False);await key('D',False)
    check('left click confirms selected lightning exactly once',get(p1,'cast_serial')==serial+1 and get(p1,'last_cast_slot')==2 and get(c1,'aiming_slot')==-1)
    reset();put(s,'cast_trigger_mode',0);serial=get(p1,'cast_serial');await key('G',True)
    check('press mode starts casting on button down',get(p1,'pending_cast')==0 and get(c1,'aiming_slot')==-1)
    await key('G',False);check('press mode release does not cast a second time',get(p1,'cast_serial')==serial+1)
    reset();put(s,'cast_trigger_mode',1);await key('F',True)
    check('self-centered Smite remains direct with no target guide',get(p1,'pending_cast')==1 and get(c1,'aiming_slot')==-1)
    await key('F',False);await tap('S')
    reset();serial=get(p2,'cast_serial');await key('Gamepad_FaceButton_Bottom',True,0)
    check('pad A holds blink preview only for P2',get(c2,'aiming_slot')==3 and get(c1,'aiming_slot')==-1 and get(p2,'pending_cast')==-1)
    await tap('Gamepad_RightThumbstick',0);await key('Gamepad_FaceButton_Bottom',False,0)
    check('R3 cancels and releasing A cannot teleport',get(c2,'aiming_slot')==-1 and get(p2,'cast_serial')==serial)
    reset();a=get(p1,'cast_serial');b=get(p2,'cast_serial');await key('Gamepad_RightTrigger',True,0);await key('Gamepad_RightTrigger',False,0)
    check('pad release casts for P2 while P1 is untouched',get(p2,'cast_serial')==b+1 and get(p1,'cast_serial')==a)
    reset();c1.add_keyboard_mouse_player();put(c2,'selected_spell',0)
    vw,vh=c2.get_viewport_size();c2.set_mouse_location(int(vw*.75),int(vh*.5))
    a=get(p1,'cast_serial');b=get(p2,'cast_serial');await key('LeftMouseButton',True)
    check('mouse-only P2 can hold its selected skill preview',get(c2,'aiming_slot')==0 and get(c1,'aiming_slot')==-1)
    await key('LeftMouseButton',False)
    check('mouse-only release casts only P2',get(p2,'cast_serial')==b+1 and get(p1,'cast_serial')==a)
    reset();c1.add_local_player();await asyncio.sleep(.05)
    await key('Gamepad_RightTrigger',True,0);await key('Gamepad_RightTrigger',True,1)
    check('two pads maintain two independent previews',get(c1,'aiming_slot')==get(c2,'aiming_slot')==0)
    check('two guides have separate owning pawns',guide_of(p1).get_owner()==p1 and guide_of(p2).get_owner()==p2)
    unreal.GameplayStatics.set_game_paused(w,False);c1.toggle_pause()
    check('pause cancels both held previews',get(c1,'aiming_slot')==get(c2,'aiming_slot')==-1)
    c1.toggle_pause();await key('Gamepad_RightTrigger',False,0);await key('Gamepad_RightTrigger',False,1)
    reset();c1.add_mixed_player();put(c1,'shop_open',True);put(c2,'shop_open',True)
    for c in [c1,c2]:put(c,'shop_top_row',0);put(c,'selected_product',0)
    unreal.GameplayStatics.set_game_paused(w,False);view.inject_pad_axis('MouseWheelAxis',0,-1);await asyncio.sleep(.08);view.inject_pad_axis('MouseWheelAxis',0,0);unreal.GameplayStatics.set_game_paused(w,True)
    check('ordinary keyboard/mouse mode wheel scrolls the spell shop',get(c1,'shop_top_row')>0)
    check('wheel does not scroll the other player shop',get(c2,'shop_top_row')==0)
    c1.scroll_shop(100);check('scroll clamps at final four rows',get(c1,'shop_top_row')==8)
    c1.scroll_shop(-100);check('scroll clamps at first family',get(c1,'shop_top_row')==0)
    for _ in range(8):await tap('Gamepad_DPad_Down',0)
    check('pad moves by one family and scrolls to mastery rows',get(c2,'selected_product')==8 and get(c2,'shop_top_row')>0)
    check('pad shop navigation is independent of keyboard player selection',get(c1,'selected_product')==0)
    balances=[get(get(p,'player_state'),'gold') for p in [p1,p2]]
    unreal.SystemLibrary.execute_console_command(w,'ke WarlockController ServerBuy 99')
    check('unimplemented product IDs cannot charge either player',balances==[get(get(p,'player_state'),'gold') for p in [p1,p2]])
    for c in [c1,c2]:put(c,'shop_open',False)
    unreal.GameplayStatics.set_game_paused(w,True);put(c1,'display_settings_open',True);put(c1,'selected_display_row',13)
    before=get(s,'cast_trigger_mode');view.inject_local_key('Right',True);view.inject_local_key('Right',False);await asyncio.sleep(.05)
    check('ESC input setting switches press/release while paused',get(s,'cast_trigger_mode')!=before)
    reloaded=unreal.new_object(unreal.WarlockUserSettings);reloaded.load_settings(True)
    check('cast trigger preference survives config reload',get(reloaded,'cast_trigger_mode')==get(s,'cast_trigger_mode'))
finally:
    put(s,'cast_trigger_mode',old);s.save_settings();c1.cancel_targeting();c2.cancel_targeting()
    for c in [c1,c2]:put(c,'shop_open',False);put(c,'display_settings_open',False)
    unreal.GameplayStatics.set_game_paused(w,False)
report={'passed':len(checks),'checks':checks,'scope':'real viewport events; physical gamepads and visual fidelity reviewed separately'}
Path(unreal.Paths.project_saved_dir(),'Validation','guided-shop-input.json').write_text(json.dumps(report,indent=2),encoding='utf8')
report
